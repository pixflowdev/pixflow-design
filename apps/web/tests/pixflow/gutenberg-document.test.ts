import { afterEach, expect, it, vi } from 'vitest';
import { webcrypto } from 'node:crypto';
import { executeGutenberg, type GutenbergApi } from '../../src/pixflow/gutenberg-native-tools';
vi.mock('../../src/pixflow/editor-style-snapshot',()=>({editorStyleSnapshot:()=>({}),editorStyleSite:()=>'',renderedEditorStyles:()=>({})}));
afterEach(()=>vi.unstubAllGlobals());
it('updates document metadata through native editing, preserves status and rejects stale or unrelated fields',async()=>{
 vi.stubGlobal('crypto',webcrypto);
 vi.stubGlobal('window',{});
 const fields:Record<string,unknown>={title:'Old title',excerpt:'Old excerpt',status:'draft',meta:{}};
 const view={getBlocks:()=>[],getSelectedBlockClientId:()=>null};
 const editor={getCurrentPostId:()=>42,getCurrentPostType:()=>'page',getEditedPostAttribute:(key:string)=>fields[key],getEditedPostContent:()=>'',isEditedPostDirty:()=>true,hasEditorUndo:()=>true,hasEditorRedo:()=>false,isSavingPost:()=>false};
 const editPost=vi.fn((value:Record<string,unknown>)=>Object.assign(fields,value));
 const wp={data:{select:(name:string)=>name==='core/editor'?editor:view,dispatch:()=>({editPost})},blocks:{}} as unknown as GutenbergApi;
 const call=(tool:string,args:Record<string,unknown>={})=>executeGutenberg(wp,{tool:'gutenberg.'+tool,postId:42,arguments:{expectedPostId:42,...args}}) as Promise<any>;
 wp.blocks.getBlockTypes=()=>[{name:'core/heading',attributes:{content:{type:'string'},style:{type:'object'}},supports:{typography:{textAlign:true}}},{name:'core/paragraph',attributes:{content:{type:'string'}}}];
 const schemas=await call('schema',{names:['core/heading','core/paragraph']});
 expect(schemas.map((s:any)=>s.name)).toEqual(['core/heading','core/paragraph']);
 await expect(call('schema',{names:['core/heading'],name:'core/paragraph'})).rejects.toThrow('either name or names');
 const initial=await call('read');
 expect(initial.blockAttributeKeys['core/heading']).toEqual(['content','style']);
 const changed=await call('document',{expectedRevision:initial.revision,attributes:{title:'Willow Desk',excerpt:'Day desks'}});
 expect(editPost).toHaveBeenCalledWith({title:'Willow Desk',excerpt:'Day desks'});
 expect(fields.status).toBe('draft');expect(changed.title).toBe('Willow Desk');expect(changed.revision).not.toBe(initial.revision);
 await expect(call('document',{expectedRevision:initial.revision,attributes:{title:'stale'}})).rejects.toThrow('changed');
 await expect(call('document',{expectedRevision:changed.revision,attributes:{status:'publish'}})).rejects.toThrow('title and excerpt');
 expect(editPost).toHaveBeenCalledTimes(1);
 wp.blocks.getBlockType=()=>({attributes:{align:{type:'string'},content:{type:'string'}}});
 wp.blocks.createBlock=vi.fn();
 await expect(call('insert',{expectedRevision:changed.revision,blocks:[{name:'core/heading',attributes:{textAlign:'center'}}]})).rejects.toThrow('Available attributes: align, content');
 expect(wp.blocks.createBlock).not.toHaveBeenCalled();
});
